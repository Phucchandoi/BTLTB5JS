// Câu 15: Object User
var u = { Name: "Max", Age: 20 };

// a) In thông tin
document.write("a) Name: " + u.Name + ", Age: " + u.Age + "<br>");

// b) Thêm thuộc tính Surname
u.Surname = "Lee";
document.write("b) Name: " + u.Name + ", Age: " + u.Age + ", Surname: " + u.Surname + "<br>");

// c) Đổi Age thành 30
u.Age = 30;
document.write("c) Name: " + u.Name + ", Age: " + u.Age + ", Surname: " + u.Surname);
